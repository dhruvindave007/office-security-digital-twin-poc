import math
from typing import Any, Dict, List, Optional


class ConversationManager:
    """Manages multi-turn conversation history formatted for Bedrock Converse API.

    Ensures valid Converse API message formats, provides history truncation to fit
    within context windows, and offers local token count estimation without external calls.
    """

    def __init__(self, max_history_turns: int = 20):
        self.max_history_turns = max_history_turns
        self._messages: List[Dict[str, Any]] = []

    def append_user_message(
        self,
        text: str,
        additional_content: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """Append a user message to history.

        Args:
            text: The text content from the user.
            additional_content: Optional list of additional Converse content blocks (e.g. image/document).
        """
        content: List[Dict[str, Any]] = []
        if text.strip():
            content.append({"text": text.strip()})
        if additional_content:
            content.extend(additional_content)

        if not content:
            raise ValueError("User message content cannot be empty.")

        msg = {"role": "user", "content": content}
        self._messages.append(msg)
        self.truncate_history(self.max_history_turns)
        return msg

    def append_assistant_message(
        self,
        text: str,
        content_blocks: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """Append an assistant response to history.

        Args:
            text: The text response generated by the assistant.
            content_blocks: Optional full content blocks returned by Bedrock.
        """
        if content_blocks:
            content = content_blocks
        elif text.strip():
            content = [{"text": text.strip()}]
        else:
            raise ValueError("Assistant message content cannot be empty.")

        msg = {"role": "assistant", "content": content}
        self._messages.append(msg)
        self.truncate_history(self.max_history_turns)
        return msg

    def build_converse_messages(self) -> List[Dict[str, Any]]:
        """Return the conversation history formatted for Bedrock Converse API.

        Validates alternating turn constraints where possible.
        """
        return list(self._messages)

    def truncate_history(self, max_turns: Optional[int] = None) -> None:
        """Truncate the message list to retain at most `max_turns` recent turns.

        A turn represents a user or assistant exchange. Ensures history starts with a 'user' role
        if possible.
        """
        limit = max_turns if max_turns is not None else self.max_history_turns
        if len(self._messages) > limit:
            self._messages = self._messages[-limit:]
            # Bedrock Converse API prefers starting with a 'user' role
            while self._messages and self._messages[0].get("role") == "assistant":
                self._messages.pop(0)

    def estimated_token_count(self) -> int:
        """Estimate the token consumption of the current conversation history.

        Uses standard heuristic of ~4 characters per token for English text.
        """
        total_chars = 0
        for msg in self._messages:
            for block in msg.get("content", []):
                if isinstance(block, dict) and "text" in block:
                    total_chars += len(block["text"])
        return math.ceil(total_chars / 4.0)

    def clear(self) -> None:
        """Clear all conversation history."""
        self._messages.clear()

    @property
    def turn_count(self) -> int:
        """Total number of messages in the conversation history."""
        return len(self._messages)

    def get_messages(self) -> List[Dict[str, Any]]:
        """Return a copy of the stored messages."""
        return list(self._messages)
